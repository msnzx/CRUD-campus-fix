-- ============================================================
-- NOTES
-- ============================================================
--
-- 1. departments.department_id is the EFFECTIVE/PRIMARY department.
--    ai_suggested_department_id stores what the AI recommended.
--
-- 2. The same pattern is used for issue type and priority:
--    issue_type_id / priority_id = effective value
--    ai_suggested_* = AI recommendation
--
-- 3. AI confidence is stored from 0.0000 to 1.0000.
--
-- 4. ticket_history should record important changes, including:
--      STATUS_CHANGED
--      DEPARTMENT_CHANGED
--      PRIORITY_CHANGED
--      ASSIGNED
--      UNASSIGNED
--      AI_CLASSIFIED
--      AI_OVERRIDE
--      COMMENT_ADDED
--      REOPEN_REQUESTED
--      REOPEN_APPROVED
--      REOPEN_DENIED
--      RESOLVED
--      CLOSED
--
-- 5. locations no longer stores building_id because:
--      locations -> floors -> buildings
--
-- 6. comments.is_internal allows staff notes to remain hidden from
--    students when the product requires private operational notes.
--
-- 7. deleted_at is a soft-delete marker. Do not physically delete
--    historical tickets that administrators may need for analytics/audit.
--
-- 8. Status transition rules should be enforced in the backend/service
--    layer rather than by a simple database CHECK constraint.
--
-- 9. Authorization MUST be enforced server-side. Hiding UI buttons is
--    not sufficient to prevent unauthorized access.
