-- Private requester <-> assigned-staff chat, and comments become internal-only.
--
-- Rules (enforced here, not in the UI):
--   * Only the ACTIVE ASSIGNEE can start the conversation. The requester can
--     reply once the assignee has sent at least one message.
--   * One thread per ticket: reassignment keeps history, the new assignee
--     continues it.
--   * Readable by the requester, the active assignee, and department/system
--     admins (read-only for admins).
--   * Nobody can send once the ticket is CLOSED or soft-deleted.
--   * comments is internal-only: department staff/admins, never the requester.
--
-- Messages have no INSERT grant; the only writer is send_ticket_message().

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

create or replace function private.can_read_ticket_messages(p_ticket_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.tickets t
    where t.ticket_id = p_ticket_id
      and (
        t.reported_by = (select auth.uid())
        or exists (
          select 1 from public.ticket_assignments a
          where a.ticket_id = t.ticket_id
            and a.unassigned_at is null
            and a.assigned_to = (select auth.uid())
        )
        or (private.is_dept_admin() and private.can_access_department(t.department_id))
      )
  );
$$;

-- Staff of the ticket's owning department (system admins span all).
-- Unlike can_access_ticket, this excludes a requester who is not staff there.
create or replace function private.is_ticket_staff(p_ticket_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select private.is_staff() and exists (
    select 1
    from public.tickets t
    where t.ticket_id = p_ticket_id
      and private.can_access_department(t.department_id)
  );
$$;

-- ---------------------------------------------------------------------------
-- ticket_messages
-- ---------------------------------------------------------------------------

create table public.ticket_messages (
  message_id bigint generated by default as identity primary key,
  ticket_id  bigint not null references public.tickets(ticket_id),
  sender_id  uuid   not null references public.users(user_id),
  message    text   not null check (length(trim(message)) > 0),
  created_at timestamptz not null default now()
);

create index ix_ticket_messages_ticket on public.ticket_messages (ticket_id, created_at);

alter table public.ticket_messages enable row level security;

revoke all on public.ticket_messages from anon, authenticated;
grant select on public.ticket_messages to authenticated;

create policy read_ticket_messages on public.ticket_messages
  for select to authenticated
  using (private.can_read_ticket_messages(ticket_id));

-- ---------------------------------------------------------------------------
-- send_ticket_message RPC
-- ---------------------------------------------------------------------------

create or replace function public.send_ticket_message(p_ticket_id bigint, p_message text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid       uuid := (select auth.uid());
  v_requester uuid;
  v_status    text;
  v_assignee  uuid;
  v_id        bigint;
begin
  if v_uid is null then
    raise exception 'Sign in to send messages';
  end if;
  if p_message is null or length(trim(p_message)) = 0 then
    raise exception 'Message cannot be empty';
  end if;

  select t.reported_by, s.name into v_requester, v_status
  from public.tickets t
  join public.statuses s on s.status_id = t.status_id
  where t.ticket_id = p_ticket_id and t.deleted_at is null
  for share of t;

  -- Same answer for "missing" and "not yours" so ids cannot be probed.
  if not found
     or not (v_uid = v_requester
             or private.can_read_ticket_messages(p_ticket_id)) then
    raise exception 'Ticket not found';
  end if;

  if v_status = 'CLOSED' then
    raise exception 'This ticket is closed. Messaging is disabled.';
  end if;

  select assigned_to into v_assignee
  from public.ticket_assignments
  where ticket_id = p_ticket_id and unassigned_at is null;

  if v_assignee is null then
    raise exception 'Messaging starts once the ticket is assigned.';
  end if;

  if v_uid = v_assignee then
    null; -- the assignee may always speak first
  elsif v_uid = v_requester then
    if not exists (
      select 1 from public.ticket_messages m
      where m.ticket_id = p_ticket_id and m.sender_id <> v_requester
    ) then
      raise exception 'Your assigned staff member will message you here first.';
    end if;
  else
    raise exception 'Only the assigned staff member and the requester can send messages';
  end if;

  insert into public.ticket_messages (ticket_id, sender_id, message)
  values (p_ticket_id, v_uid, trim(p_message))
  returning message_id into v_id;

  return v_id;
end;
$$;

revoke execute on function public.send_ticket_message(bigint, text) from public, anon;
grant  execute on function public.send_ticket_message(bigint, text) to authenticated;

-- ---------------------------------------------------------------------------
-- Notify the other party. Isolated inside private.notify, so a failure never
-- rolls back the message.
-- ---------------------------------------------------------------------------

create or replace function public.notify_ticket_message()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_requester uuid;
  v_assignee  uuid;
begin
  select reported_by into v_requester from public.tickets where ticket_id = new.ticket_id;
  select assigned_to into v_assignee from public.ticket_assignments
   where ticket_id = new.ticket_id and unassigned_at is null;

  if new.sender_id = v_requester then
    perform private.notify(v_assignee, new.ticket_id, 'MESSAGE',
      'The requester replied on ' || private.ticket_label(new.ticket_id) || '.');
  else
    perform private.notify(v_requester, new.ticket_id, 'MESSAGE',
      'New message about your ticket ' || private.ticket_label(new.ticket_id) || '.');
  end if;
  return new;
end;
$$;

create trigger notify_ticket_message
  after insert on public.ticket_messages
  for each row execute function public.notify_ticket_message();

revoke execute on function public.notify_ticket_message() from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- comments: internal-only
-- ---------------------------------------------------------------------------

update public.comments set is_internal = true where not is_internal;

alter table public.comments alter column is_internal set default true;
alter table public.comments add constraint comments_internal_only check (is_internal);

drop policy if exists read_ticket_comments   on public.comments;
drop policy if exists insert_ticket_comment  on public.comments;

create policy read_ticket_comments on public.comments
  for select to authenticated
  using (private.is_ticket_staff(ticket_id));

create policy insert_ticket_comment on public.comments
  for insert to authenticated
  with check (
    private.is_ticket_staff(ticket_id)
    and user_id = (select auth.uid())
    and is_internal
  );

-- The requester branch of this trigger is dead now and internal rows never
-- notified anyone.
drop trigger if exists notify_comment on public.comments;
drop function if exists public.notify_comment();
